#!/usr/bin/env node
// 生成 push.json：推送载荷加密的测试向量（src/push.ts 的格式）。这里只用 node:crypto（OpenSSL 的 X25519、HKDF、ChaCha20-Poly1305、
// HMAC），与 src/push.ts 用的 @noble/* 是两份独立实现；测试只读生成好的 JSON。
//   node packages/noise/test-vectors/pushgen.mjs > packages/noise/test-vectors/push.json
// 密钥由固定的种子经 SHA-256 得到，结果每次都一样。

import {
  createCipheriv,
  createHash,
  createHmac,
  createPrivateKey,
  createPublicKey,
  diffieHellman,
  hkdfSync,
} from 'node:crypto';

const LABEL = 'wevir-push/1';

const seed = (name) => createHash('sha256').update(`wevir push vector ${name}`).digest();

function x25519(secret) {
  // RFC 8410 的 PKCS#8 前缀加 32 字节私钥。
  const der = Buffer.concat([Buffer.from('302e020100300506032b656e04220420', 'hex'), secret]);
  const privateKey = createPrivateKey({ key: der, format: 'der', type: 'pkcs8' });
  const publicKey = createPublicKey(privateKey)
    .export({ format: 'der', type: 'spki' })
    .subarray(-32);
  return { privateKey, publicKey };
}

function publicKeyObject(raw) {
  const der = Buffer.concat([Buffer.from('302a300506032b656e032100', 'hex'), raw]);
  return createPublicKey({ key: der, format: 'der', type: 'spki' });
}

function header(counter) {
  const out = Buffer.alloc(9);
  out[0] = 1;
  out.writeBigUInt64BE(BigInt(counter), 1);
  return out;
}

function nonce(counter) {
  const out = Buffer.alloc(12);
  out.writeBigUInt64LE(BigInt(counter), 4);
  return out;
}

const cases = [
  {
    name: 'approval',
    counter: 1,
    plaintext:
      '{"v":1,"id":"approval:apr_1","kind":"approval","category":"action","title":"Fix the build","host":"Mac","createdAt":"2026-10-23T00:00:00.000Z"}',
    collapseKey: 'session:ses_01JA2B3C4D5E6F7G8H9JKMNPQR',
  },
  {
    name: 'timestamp counter, non-ASCII title',
    counter: 1_792_368_000_000,
    plaintext:
      '{"v":1,"id":"completed:trn_1","kind":"completed","category":"completion","title":"修复构建 ✓","host":"工作室的 Mac","createdAt":"2026-10-23T00:00:00.000Z"}',
    collapseKey: 'automation:aut_1',
  },
  {
    name: 'largest counter, empty plaintext',
    counter: Number.MAX_SAFE_INTEGER,
    plaintext: '',
    collapseKey: '',
  },
];

const host = x25519(seed('host'));
const device = x25519(seed('device'));
const shared = diffieHellman({
  privateKey: host.privateKey,
  publicKey: publicKeyObject(device.publicKey),
});
const sharedFromDevice = diffieHellman({
  privateKey: device.privateKey,
  publicKey: publicKeyObject(host.publicKey),
});
if (!shared.equals(sharedFromDevice)) throw new Error('X25519 is not symmetric');
const key = Buffer.from(
  hkdfSync(
    'sha256',
    shared,
    Buffer.from(LABEL),
    Buffer.concat([Buffer.from(`${LABEL} payload key`), host.publicKey, device.publicKey]),
    32,
  ),
);

const vectors = cases.map(({ name, counter, plaintext, collapseKey }) => {
  const head = header(counter);
  const cipher = createCipheriv('chacha20-poly1305', key, nonce(counter), { authTagLength: 16 });
  cipher.setAAD(head, { plaintextLength: Buffer.byteLength(plaintext) });
  const body = Buffer.concat([
    cipher.update(plaintext, 'utf8'),
    cipher.final(),
    cipher.getAuthTag(),
  ]);
  const collapse = createHmac('sha256', key)
    .update(`${LABEL} collapse\n${collapseKey}`)
    .digest()
    .subarray(0, 16);
  return {
    name,
    counter,
    plaintext,
    envelope: Buffer.concat([head, body]).toString('base64url'),
    collapse_key: collapseKey,
    collapse_key_mac: collapse.toString('base64url'),
  };
});

process.stdout.write(
  `${JSON.stringify(
    {
      source:
        'Generated by packages/noise/test-vectors/pushgen.mjs with node:crypto (OpenSSL), independent of src/push.ts. Public domain test data.',
      host_secret: seed('host').toString('hex'),
      host_public: host.publicKey.toString('hex'),
      device_secret: seed('device').toString('hex'),
      device_public: device.publicKey.toString('hex'),
      shared_secret: shared.toString('hex'),
      push_key: key.toString('hex'),
      vectors,
    },
    null,
    2,
  )}\n`,
);
