// Android 的明文 `ws://`（Expo config plugin，prebuild 时写进 android/）。
//
// 直连 Host 是 `ws://<局域网或 Tailscale 地址>:<端口>`，内容全在 Noise 里（端到端加密与认证，ADR-0017 §2），外面不再套 TLS。Android 9 起
// 默认禁止明文，React Native 的 WebSocket 走 OkHttp，会因 `CLEARTEXT communication … not permitted` 失败。网络安全配置的
// `domain-config` 只能按主机名或单个 IP 放行、不能写网段，而 Host 的地址事先不知道（DHCP、Tailscale 的 100.64.0.0/10），所以只能在
// `base-config` 放开明文；收得最紧的做法是：
// - 只放开明文，信任锚仍只有系统证书（不信任用户装的 CA），`wss://` 中继照常校验证书；
// - App 里除了到 Host 的 WebSocket 不发任何 HTTP 请求（不用 `fetch` 访问 Host，host-api.md §1.1），开发构建连 Metro 本来就要明文。
// iOS 不用改：WebSocket 不受 ATS 管（Spike §8.2），保留 Expo 默认的 ATS 配置。

const { AndroidConfig, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

const CONFIG_NAME = 'wevir_network_security_config';

const XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/mobile/plugins/with-android-cleartext.js; see that file for why cleartext is allowed. -->
<network-security-config>
  <base-config cleartextTrafficPermitted="true">
    <trust-anchors>
      <certificates src="system" />
    </trust-anchors>
  </base-config>
</network-security-config>
`;

module.exports = function withAndroidCleartext(config) {
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(path.join(dir, `${CONFIG_NAME}.xml`), XML);
      return cfg;
    },
  ]);
  return withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    app.$['android:networkSecurityConfig'] = `@xml/${CONFIG_NAME}`;
    // 有网络安全配置时 `usesCleartextTraffic` 不起作用，删掉免得两处说法不一。
    delete app.$['android:usesCleartextTraffic'];
    return cfg;
  });
};
