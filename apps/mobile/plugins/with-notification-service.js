// iOS 的通知服务扩展（Expo config plugin，prebuild 时写进 ios/）。推送网关送来的提醒只有通用文案与加密载荷，扩展在手机上解密并改写
// 标题与正文（plugins/notification-service/NotificationService.swift 的文件头）。这里做三件事：
// - 把 notification-service/ 下的 Swift 拷进 ios/WevirNotificationService/，生成 Info.plist（App Group 名写在 `WevirAppGroup`）、
//   entitlements（与 App 同一个 App Group，读共享钥匙串与容器）与 PushStrings.json（从 native-strings/*.json 的
//   `ios["Localizable.strings"]` 取，十种语言）；
// - 在 Xcode 工程里加一个 app extension target（`<App 的 bundle ID>.NotificationService`），嵌进 App；
// - 版本号、部署目标、签名团队跟着 App 的 target。
//
// 扩展只用系统框架（Foundation、CryptoKit、Security、UserNotifications），不进 Podfile。真机构建要在开发者账号里给扩展建 App ID
// 并打开同一个 App Group。

const { withDangerousMod, withXcodeProject } = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

const TARGET = 'WevirNotificationService';
const SOURCES = ['NotificationService.swift', 'PushCrypto.swift'];
const RESOURCES = ['PushStrings.json'];
const STRING_KEYS = /^WEVIR_PUSH_/;

function infoPlist(appGroup) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by apps/mobile/plugins/with-notification-service.js. -->
<plist version="1.0">
<dict>
  <key>CFBundleDevelopmentRegion</key>
  <string>$(DEVELOPMENT_LANGUAGE)</string>
  <key>CFBundleDisplayName</key>
  <string>Wevir</string>
  <key>CFBundleExecutable</key>
  <string>$(EXECUTABLE_NAME)</string>
  <key>CFBundleIdentifier</key>
  <string>$(PRODUCT_BUNDLE_IDENTIFIER)</string>
  <key>CFBundleInfoDictionaryVersion</key>
  <string>6.0</string>
  <key>CFBundleName</key>
  <string>$(PRODUCT_NAME)</string>
  <key>CFBundlePackageType</key>
  <string>$(PRODUCT_BUNDLE_PACKAGE_TYPE)</string>
  <key>CFBundleShortVersionString</key>
  <string>$(MARKETING_VERSION)</string>
  <key>CFBundleVersion</key>
  <string>$(CURRENT_PROJECT_VERSION)</string>
  <key>NSExtension</key>
  <dict>
    <key>NSExtensionPointIdentifier</key>
    <string>com.apple.usernotifications.service</string>
    <key>NSExtensionPrincipalClass</key>
    <string>$(PRODUCT_MODULE_NAME).NotificationService</string>
  </dict>
  <key>WevirAppGroup</key>
  <string>${appGroup}</string>
</dict>
</plist>
`;
}

function entitlements(appGroup) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>com.apple.security.application-groups</key>
  <array>
    <string>${appGroup}</string>
  </array>
</dict>
</plist>
`;
}

/** `locales` 里每种语言的扩展文案（`ios["Localizable.strings"]` 里 `WEVIR_PUSH_` 开头的键）。 */
function pushStrings(config, projectRoot) {
  const out = {};
  for (const [lang, file] of Object.entries(config.locales ?? {})) {
    const json =
      typeof file === 'string'
        ? JSON.parse(fs.readFileSync(path.resolve(projectRoot, file), 'utf8'))
        : file;
    const strings = json?.ios?.['Localizable.strings'] ?? {};
    out[lang] = Object.fromEntries(
      Object.entries(strings).filter(([key]) => STRING_KEYS.test(key)),
    );
  }
  return out;
}

function withExtensionFiles(config, { appGroup }) {
  return withDangerousMod(config, [
    'ios',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, TARGET);
      await fs.promises.mkdir(dir, { recursive: true });
      for (const file of SOURCES) {
        await fs.promises.copyFile(
          path.join(__dirname, 'notification-service', file),
          path.join(dir, file),
        );
      }
      await fs.promises.writeFile(path.join(dir, 'Info.plist'), infoPlist(appGroup));
      await fs.promises.writeFile(path.join(dir, `${TARGET}.entitlements`), entitlements(appGroup));
      await fs.promises.writeFile(
        path.join(dir, 'PushStrings.json'),
        `${JSON.stringify(pushStrings(cfg, cfg.modRequest.projectRoot), null, 2)}\n`,
      );
      return cfg;
    },
  ]);
}

function withExtensionTarget(config) {
  return withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;
    if (project.pbxTargetByName(TARGET) !== null && project.pbxTargetByName(TARGET) !== undefined) {
      return cfg;
    }
    const objects = project.hash.project.objects;
    objects.PBXTargetDependency ??= {};
    objects.PBXContainerItemProxy ??= {};

    const bundleId = `${cfg.ios?.bundleIdentifier ?? 'si.wevir.mobile'}.NotificationService`;
    const files = [...SOURCES, ...RESOURCES, 'Info.plist', `${TARGET}.entitlements`];
    const group = project.addPbxGroup(files, TARGET, TARGET);
    const mainGroup = project.getFirstProject().firstProject.mainGroup;
    project.addToPbxGroup(group.uuid, mainGroup);

    const appTarget = project.getFirstTarget();
    const target = project.addTarget(TARGET, 'app_extension', TARGET, bundleId);
    project.addBuildPhase(SOURCES, 'PBXSourcesBuildPhase', 'Sources', target.uuid);
    project.addBuildPhase(RESOURCES, 'PBXResourcesBuildPhase', 'Resources', target.uuid);
    project.addBuildPhase([], 'PBXFrameworksBuildPhase', 'Frameworks', target.uuid);

    // App 的 target 的设置：部署目标跟着它走。版本号、构建号与签名团队从配置取：Expo 自己写 App target 的这几项的 mod 与本插件
    // 的先后不定，从 App target 抄可能抄到空值或默认值；扩展的 CFBundleVersion 与短版本号跟 App 不一致时 App Store Connect 拒收。
    const configurations = project.pbxXCBuildConfigurationSection();
    const appList = project.pbxXCConfigurationList()[appTarget.firstTarget.buildConfigurationList];
    const appSettings = {};
    for (const ref of appList.buildConfigurations) {
      appSettings[ref.comment] = configurations[ref.value].buildSettings;
    }
    const team = cfg.ios?.appleTeamId ?? appSettings.Release?.DEVELOPMENT_TEAM;
    const extensionList =
      project.pbxXCConfigurationList()[target.pbxNativeTarget.buildConfigurationList];
    for (const ref of extensionList.buildConfigurations) {
      const settings = configurations[ref.value].buildSettings;
      const app = appSettings[ref.comment] ?? {};
      Object.assign(settings, {
        INFOPLIST_FILE: `${TARGET}/Info.plist`,
        CODE_SIGN_ENTITLEMENTS: `${TARGET}/${TARGET}.entitlements`,
        CODE_SIGN_STYLE: 'Automatic',
        SWIFT_VERSION: '5.0',
        TARGETED_DEVICE_FAMILY: '"1"',
        GENERATE_INFOPLIST_FILE: 'NO',
        IPHONEOS_DEPLOYMENT_TARGET: app.IPHONEOS_DEPLOYMENT_TARGET ?? '16.4',
        MARKETING_VERSION: cfg.version ?? app.MARKETING_VERSION ?? '1.0',
        CURRENT_PROJECT_VERSION: cfg.ios?.buildNumber ?? app.CURRENT_PROJECT_VERSION ?? '1',
        ...(team !== undefined && { DEVELOPMENT_TEAM: team }),
      });
    }
    return cfg;
  });
}

module.exports = function withNotificationService(config, props = {}) {
  const appGroup = props.appGroup;
  if (typeof appGroup !== 'string' || appGroup === '') {
    throw new Error('with-notification-service: appGroup is required');
  }
  config = withExtensionFiles(config, { appGroup });
  return withExtensionTarget(config);
};
