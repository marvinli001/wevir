// Android 的原生主题（Expo config plugin，prebuild 时写进 android/）：深色模式的窗口与启动画面底色、系统提示框的样式。
//
// - Expo 生成的主题只有浅色：窗口底色 `activityBackground` 取 app.config 的 `backgroundColor`，Android 12 起的系统启动画面没设底色，
//   深色模式下启动是一整屏白。这里给两者加深色值（values-night），与 src/theme.ts 的页面底色相同。
// - React Native 的 `Alert` 是 AppCompat 的提示框：默认灰底、直角、青色的全大写按钮，与“静器”不符。换成表面色圆角卡片（28dp，
//   Material 3 的对话框圆角）、墨色按钮、按钮文字不转大写，深浅色各一组。
// 颜色与 src/theme.ts 的 LIGHT / DARK 保持一致。

const {
  AndroidConfig,
  withAndroidColors,
  withAndroidColorsNight,
  withAndroidStyles,
  withDangerousMod,
} = require('expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

// 浅色的窗口底色由 Expo 按 app.config 的 `backgroundColor` 写入，这里只补深色。
const LIGHT = {
  wevir_dialog_surface: '#ffffff',
  wevir_dialog_text: '#1a1a17',
  wevir_dialog_secondary: '#45433d',
};
const DARK = {
  activityBackground: '#0c0d10',
  // 比页面与卡片亮一档，压在遮罩上分得出层次（Material 3 的对话框也用更高的表面色）。
  wevir_dialog_surface: '#212227',
  wevir_dialog_text: '#eeede8',
  wevir_dialog_secondary: '#c4c3bd',
};

const DIALOG_BACKGROUND = 'wevir_dialog_background';
const DIALOG_DRAWABLE = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by apps/mobile/plugins/with-android-theme.js. -->
<inset xmlns:android="http://schemas.android.com/apk/res/android"
  android:insetLeft="16dp" android:insetTop="16dp" android:insetRight="16dp" android:insetBottom="16dp">
  <shape android:shape="rectangle">
    <corners android:radius="28dp" />
    <solid android:color="@color/wevir_dialog_surface" />
  </shape>
</inset>
`;

function assignColors(xml, colors) {
  for (const [name, value] of Object.entries(colors)) {
    xml = AndroidConfig.Colors.assignColorValue(xml, { name, value });
  }
  return xml;
}

function style(name, parent, items) {
  return {
    $: { name, parent },
    item: Object.entries(items).map(([key, value]) => ({ $: { name: key }, _: value })),
  };
}

function setStyle(xml, next) {
  const styles = (xml.resources.style ?? []).filter((s) => s.$.name !== next.$.name);
  xml.resources.style = [...styles, next];
  return xml;
}

module.exports = function withAndroidTheme(config) {
  config = withAndroidColors(config, (cfg) => {
    cfg.modResults = assignColors(cfg.modResults, LIGHT);
    return cfg;
  });
  config = withAndroidColorsNight(config, (cfg) => {
    cfg.modResults = assignColors(cfg.modResults, DARK);
    return cfg;
  });
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/drawable');
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(path.join(dir, `${DIALOG_BACKGROUND}.xml`), DIALOG_DRAWABLE);
      return cfg;
    },
  ]);
  return withAndroidStyles(config, (cfg) => {
    let xml = cfg.modResults;
    xml = setStyle(
      xml,
      style('WevirAlertDialogButton', 'Widget.AppCompat.Button.ButtonBar.AlertDialog', {
        'android:textAllCaps': 'false',
        'android:textColor': '@color/wevir_dialog_text',
      }),
    );
    xml = setStyle(
      xml,
      style('WevirAlertDialog', 'ThemeOverlay.AppCompat.Dialog.Alert', {
        'android:windowBackground': `@drawable/${DIALOG_BACKGROUND}`,
        colorAccent: '@color/wevir_dialog_text',
        'android:textColorPrimary': '@color/wevir_dialog_text',
        'android:textColorSecondary': '@color/wevir_dialog_secondary',
        'android:textColorAlertDialogListItem': '@color/wevir_dialog_text',
        buttonBarButtonStyle: '@style/WevirAlertDialogButton',
        buttonBarPositiveButtonStyle: '@style/WevirAlertDialogButton',
        buttonBarNegativeButtonStyle: '@style/WevirAlertDialogButton',
        buttonBarNeutralButtonStyle: '@style/WevirAlertDialogButton',
      }),
    );
    for (const [name, value] of Object.entries({
      alertDialogTheme: '@style/WevirAlertDialog',
      'android:alertDialogTheme': '@style/WevirAlertDialog',
    })) {
      xml = AndroidConfig.Styles.assignStylesValue(xml, {
        add: true,
        name,
        value,
        parent: AndroidConfig.Styles.getAppThemeGroup(),
      });
    }
    // Android 12 起系统启动画面的底色；更早的系统没有这个属性，启动时直接是窗口底色。
    xml = AndroidConfig.Styles.assignStylesValue(xml, {
      add: true,
      name: 'android:windowSplashScreenBackground',
      value: '@color/activityBackground',
      targetApi: '31',
      parent: { name: 'Theme.App.SplashScreen', parent: 'AppTheme' },
    });
    cfg.modResults = xml;
    return cfg;
  });
};
